  <h1>Cara menggunakan E-FoodHub</h1>
  <div class="panel mt-4">
    <h2>Untuk pembeli</h2>
    <ol>
      <li>Daftar akaun dan log masuk.</li>
      <li>Cari produk melalui kotak carian, kategori atau halaman kedai. Tekan <strong>Tambah ke troli</strong>.</li>
      <li>Di halaman <strong>Troli</strong>, semak kuantiti. Troli boleh mengandungi produk dari beberapa kedai — setiap kedai akan menerima bahagian pesanannya sendiri.</li>
      <li>Tekan <strong>Teruskan ke pesanan</strong>, isi nama dan nombor telefon, dan pilih kaedah bayaran.</li>
      <li>Ikuti status di <strong>Pesanan Saya</strong>: Menunggu → Disahkan → Sedang disediakan → Sedia diambil → Selesai.</li>
      <li>Ambil pesanan di lokasi gerai dan tunjukkan nombor pesanan anda.</li>
    </ol>
    <p class="mb-0">Anda boleh membatalkan bahagian pesanan yang masih <em>Menunggu</em>. Selepas penjual mengesahkannya, hubungi penjual terus jika ada perubahan.</p>
  </div>
  <div class="panel">
    <h2>Kaedah bayaran</h2>
    <p><strong>Tunai semasa ambil</strong> — bayar kepada penjual apabila mengambil pesanan. Penjual menandakan bayaran diterima apabila pesanan selesai.</p>
    <p class="mb-0"><strong>Bayaran dalam talian (simulasi)</strong> — disediakan untuk tujuan demonstrasi projek sahaja. Tiada wang sebenar dipindahkan dan tiada maklumat kad atau bank diminta.</p>
  </div>
  <div class="panel">
    <h2>Untuk penjual</h2>
    <ol class="mb-0">
      <li>Log masuk dan pilih <strong>Buka kedai</strong>. Isi nama kedai, penerangan, telefon dan lokasi pengambilan.</li>
      <li>Tunggu kelulusan pentadbir. Anda akan menerima notifikasi.</li>
      <li>Selepas diluluskan, tambah produk di <strong>Pengurusan Produk</strong>. Produk baharu mungkin perlu diluluskan sebelum dipaparkan.</li>
      <li>Urus pesanan di <strong>Pengurusan Pesanan</strong>: sahkan, sediakan, tandakan sedia diambil, kemudian selesai.</li>
    </ol>
  </div>
